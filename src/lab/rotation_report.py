"""Write research/lab/meme_rotation/REPORT.md and top.json from dev_results.json (+ holdout.json
when it exists). Every number comes from those files (src/lab/rotation.py). Run from src/:
    ../.venv/bin/python -m lab.rotation report
"""
from __future__ import annotations

import json
import math

from .rotation import OUT, STRATS

NOTES_FILE = OUT / "verdict_notes.md"     # hand-written interpretation, kept separate


def pct(x, nd=1, sign=True):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return f"{100 * x:+.{nd}f}%" if sign else f"{100 * x:.{nd}f}%"


def r_(x, nd=3):
    return "n/a" if x is None else f"{x:+.{nd}f}"


def main():
    dev = json.loads((OUT / "dev_results.json").read_text())
    hp = OUT / "holdout.json"
    ho = json.loads(hp.read_text()) if hp.exists() else None
    S = dev["strategies"]
    b = dev["bench"]
    bench_cagr = max(b["btc_perp"]["cagr"], b["btc_spot"]["cagr"])
    status = {}
    for sid, s in S.items():
        fails = list(s["gates_failed"])
        if ho is None:
            fails.append("holdout not run yet")
        elif not ho["strategies"][sid]["positive"]:
            h = ho["strategies"][sid]["base"]
            fails.append(f"holdout not positive after costs ({pct(h['total_return'])}, "
                         f"{h['trades']} trades)")
        status[sid] = fails
    qual = [sid for sid, f in status.items() if not f]
    nvar = len(dev["variants"])
    L = ["# Meme rotation - LAB report\n",
         "Generated by `src/lab/rotation_report.py` from `dev_results.json`"
         + (" and `holdout.json`" if ho else "") + " (code `src/lab/rotation.py`, design frozen "
         "in `DESIGN.md` before any backtest). Binance USDT-M meme perps, delisted coins "
         "included, EUR100 (110 USDT) paper account, 1% risk per position, max 3 positions, "
         "<= 3x leverage, taker 0.05% + 10bp slippage per side, real funding. Paper only.\n",
         "## Verdict\n"]
    if qual:
        L.append(f"**{len(qual)} of 5 strategies QUALIFY: {', '.join(qual)}** (paper only).\n")
    else:
        L.append("**No rotation strategy qualifies. None of R1-R5 passes every gate, so LAB "
                 "does not recommend trading any of them, not even on paper as a candidate "
                 "for live.**\n")
    if NOTES_FILE.exists():
        L.append(NOTES_FILE.read_text().strip() + "\n")
    L.append(f"- Variants tried: **{nvar}** (R1 18, R2 9 + 1 reference 'monitor off', R3 9, "
             "R4 3, R5 18). Holdout runs: one per strategy (5), default parameters only.")
    for sid in S:
        f = status[sid]
        L.append(f"- **{sid}** {S[sid]['name']}: " + ("QUALIFIED" if not f else
                 "NOT QUALIFIED - " + "; ".join(f)) + ".")
    L.append("")
    # ---------------------------------------------------------------- headline table
    L.append("## All strategies and variants\n")
    L.append("dev OOS = 2024-11..2026-04 (18 months, default and grid variants, base costs); "
             "WF = stitched walk-forward test quarters 2023-11..2026-04 (strategy level, shown on "
             "the default row); 2x = fees x2 AND slippage x2; ex-best = 2x costs with the best "
             "dev-OOS coin removed from the universe; holdout = 2026-05..2026-10, run once, "
             "default only. Return = total return of the 110 USDT account over the window. "
             "Max DD and worst month are mark-to-market at daily closes. Skipped = would-be "
             "entries below the 5 USDT minimum notional (EUR100 constraint).\n")
    L.append("| strat | params | dev OOS trades | dev OOS exp R | dev OOS return | WF R / return "
             "| 2x return | ex-best 2x return (coin) | holdout return (trades) | max DD | worst "
             "month | losing streak | skipped min-notional | dev IS return |")
    L.append("|---|---|---:|---:|---:|---|---:|---|---|---:|---:|---:|---:|---:|")
    for v in dev["variants"]:
        sid = v["strategy"]
        d = v["default"]
        wf = S[sid]["wf"] if d else None
        h = ho["strategies"][sid] if (ho and d) else None
        L.append("| {} | {}{} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
            sid, v["params"].replace("|", ", "), " **(default)**" if d else "", v["oos_trades"], r_(v["oos_exp_R"]),
            pct(v["oos_total_return"]),
            f"{wf['total_R']:+.1f}R / {pct(wf['total_return'])}" if wf else "",
            pct(v["oos_2x_total_return"]),
            f"{pct(v['ex_best_2x_total_return'])} ({v['best_coin']})" if v["best_coin"] else "n/a",
            (f"{pct(h['base']['total_return'])} ({h['base']['trades']})" if h else
             ("not run" if d else "")),
            pct(v["max_dd_mtm"], sign=False), pct(v["worst_month"]), v["losing_streak"],
            v["skipped_min_notional"], pct(v["is_total_return"])))
    L.append("")
    # ---------------------------------------------------------------- gates
    L.append("## Gates on the default variants\n")
    L.append(f"Benchmarks over dev OOS (after costs): BTC buy-and-hold perp CAGR "
             f"{pct(b['btc_perp']['cagr'])} (total {pct(b['btc_perp']['total_return'])}), "
             f"spot-like {pct(b['btc_spot']['cagr'])} (total {pct(b['btc_spot']['total_return'])}),"
             f" equal-weight meme basket {pct(b['meme_basket']['cagr'])} (total "
             f"{pct(b['meme_basket']['total_return'])}, max DD "
             f"{pct(b['meme_basket']['max_dd'], sign=False)}, avg "
             f"{b['meme_basket']['avg_coins']:.0f} coins). The BTC gate uses the stricter "
             f"({pct(bench_cagr)}).\n")
    L.append("| strat | trades >= 50 | 2x costs positive | beats BTC B&H | beats meme basket | "
             "WF positive | ex-best positive (2x) | neighbours positive | min-notional skips | "
             "holdout positive | status |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for sid, s in S.items():
        d = s["default"]
        o = d["oos"]
        o2 = d["oos_2x"]
        xb = d.get("oos_2x_ex_best") or {}
        wf = s["wf"]

        def yn(ok, txt):
            return ("PASS " if ok else "FAIL ") + txt
        pos2 = o2["trades"] > 0 and o2["total_return"] > 0 and (o2["exp_R"] or -1) > 0
        posx = bool(xb) and xb["trades"] > 0 and xb["total_return"] > 0 and (xb["exp_R"] or -1) > 0
        h = ho["strategies"][sid] if ho else None
        L.append("| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |".format(
            sid, yn(o["trades"] >= 50, str(o["trades"])),
            yn(pos2, f"{pct(o2['total_return'])}, {r_(o2['exp_R'])}R"),
            yn(o["cagr"] > bench_cagr, f"CAGR {pct(o['cagr'])}"),
            yn(o["cagr"] > b["meme_basket"]["cagr"], f"CAGR {pct(o['cagr'])}"),
            yn(wf["total_R"] > 0 and wf["total_return"] > 0,
               f"{wf['total_R']:+.1f}R, {pct(wf['total_return'])}"),
            yn(posx, f"{pct(xb.get('total_return'))} w/o {d['best_coin']}"),
            yn(s["robust_neighbour_pos_share"] >= 0.5, f"{s['robust_neighbour_pos_share']:.0%}"),
            yn(o["min_notional_skip_share"] <= 0.5 and o["trades"] > 0,
               f"{o['skipped_min_notional']} ({o['min_notional_skip_share']:.0%})"),
            ("not run" if h is None else yn(h["positive"], pct(h["base"]["total_return"]))),
            "QUALIFIED" if not status[sid] else "NOT QUALIFIED"))
    L.append("")
    # ---------------------------------------------------------------- holdout
    L.append("## Final holdout (2026-05-01 .. 2026-10-31), run once, default parameters\n")
    if ho is None:
        L.append("Not run yet.\n")
    else:
        hb = ho["bench"]
        L.append(f"Run {ho['generated'][:16]} UTC. Benchmarks over the holdout: BTC perp "
                 f"{pct(hb['btc_perp']['total_return'])}, BTC spot-like "
                 f"{pct(hb['btc_spot']['total_return'])}, meme basket "
                 f"{pct(hb['meme_basket']['total_return'])} (total returns, 6 months).\n")
        L.append("| strat | trades | win | exp R | total return | 2x costs return | max DD | "
                 "worst month | losing streak | skipped min-notional | best / worst coin (R) |")
        L.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|")
        for sid, h in ho["strategies"].items():
            m, m2 = h["base"], h["both2x"]
            bs = h["by_symbol"]
            ks = list(bs)
            bw = f"{ks[-1]} {bs[ks[-1]]:+.1f} / {ks[0]} {bs[ks[0]]:+.1f}" if ks else "-"
            L.append(f"| {sid} | {m['trades']} | {pct(m['win_rate'], 0, False)} | "
                     f"{r_(m['exp_R'])} | {pct(m['total_return'])} | {pct(m2['total_return'])} | "
                     f"{pct(m['max_dd_mtm'], sign=False)} | {pct(m['worst_month'])} | "
                     f"{m['losing_streak']} | {m['skipped_min_notional']} | {bw} |")
        L.append("")
    # ---------------------------------------------------------------- details
    L.append("## Detail per strategy (default variant, dev OOS unless stated)\n")
    for sid, s in S.items():
        d = s["default"]
        o = d["oos"]
        L.append(f"### {sid} - {s['name']}\n")
        L.append(f"*{s['line']}*  Default `{s['default_key']}`"
                 + (f"; R4 base = **{s['r4_base']}** (highest dev-OOS CAGR of R1-R3)"
                    if s.get("r4_base") else "") + ".\n")
        mnot = "n/a" if o["median_notional"] is None else f"{o['median_notional']:.1f}"
        L.append(f"- dev OOS: {o['trades']} trades ({o['long_trades']} long / {o['short_trades']}"
                 f" short, {o['symbols']} coins), win {pct(o['win_rate'], 0, False)}, "
                 f"exp {r_(o['exp_R'])}R, PF {o['pf'] if o['pf'] is None else round(o['pf'], 2)}"
                 f", return {pct(o['total_return'])} (CAGR {pct(o['cagr'])}), max DD MTM "
                 f"{pct(o['max_dd_mtm'], sign=False)} (closed-trade "
                 f"{pct(o['max_dd_closed'], sign=False)}), worst month {pct(o['worst_month'])} "
                 f"({o['worst_month_id']}), longest losing streak {o['losing_streak']}, exposure "
                 f"{pct(o['exposure'], 0, False)}, median notional "
                 f"{mnot}"
                 f" USDT. Skips: {o['skipped']}.")
        L.append(f"- dev IS (2022-11..2024-10, secondary): {d['is']['trades']} trades, exp "
                 f"{r_(d['is']['exp_R'])}R, return {pct(d['is']['total_return'])}.")
        L.append(f"- Double costs: {o['trades'] and d['oos_2x']['trades']} trades, exp "
                 f"{r_(d['oos_2x']['exp_R'])}R, return {pct(d['oos_2x']['total_return'])}. Best "
                 f"coin {d['best_coin']} ({d['best_coin_R']:+.1f}R"
                 + (f", {pct(d['best_coin_share'], 0, False)} of total R" if d['best_coin_share']
                    else "") + "); without it at 2x costs: "
                 + (f"{d['oos_2x_ex_best']['trades']} trades, exp {r_(d['oos_2x_ex_best']['exp_R'])}"
                    f"R, return {pct(d['oos_2x_ex_best']['total_return'])}."
                    if d.get("oos_2x_ex_best") else "n/a."))
        hv = s["by_half"]
        L.append("- Halves: " + "; ".join(f"{k}: {x['trades']} trades, exp {r_(x['exp_R'])}R, "
                                           f"return {pct(x['total_return'])} (BTC spot-like "
                                           f"{pct(x['btc_spot'])})" for k, x in hv.items()) + ".")
        rg = s["regimes"]
        if rg:
            L.append("- BTC regimes (entry month): " + "; ".join(
                f"{k} {x['trades']} trades, exp {r_(x['exp_R'])}R, total {x['total_R']:+.1f}R"
                for k, x in rg.items()) + ".")
        mc = s["mc"]
        if mc:
            L.append(f"- Monte Carlo (5,000 each): reshuffle 95th-pct max DD "
                     f"{pct(mc['shuffle_dd_p95'], sign=False)}, P(ruin 50%) "
                     f"{pct(mc['shuffle_p_ruin'], 2, False)}; bootstrap 95th-pct max DD "
                     f"{pct(mc['bootstrap_dd_p95'], sign=False)}, P(ruin) "
                     f"{pct(mc['bootstrap_p_ruin'], 2, False)}, 5th-pct final equity "
                     f"{mc['bootstrap_final_p5']:.2f}x.")
        wf = s["wf"]
        L.append(f"- Walk-forward {wf['span']}: {wf['trades']} trades, {wf['total_R']:+.1f}R, "
                 f"return {pct(wf['total_return'])}, max DD {pct(wf['max_dd_mtm'], sign=False)}; "
                 f"dev-OOS part {wf['dev_oos_part_trades']} trades {wf['dev_oos_part_R']:+.1f}R. "
                 "Picks: " + ", ".join(f"{p['test']} `{p['params']}` {p['test_R']:+.1f}R"
                                       for p in wf["picks"]) + ".")
        L.append(f"- Robustness: {s['robust_neighbour_pos_share']:.0%} of one-step neighbours "
                 f"positive ({', '.join(s['neighbours'])}); whole grid "
                 f"{s['robust_grid_pos_share']:.0%}.")
        bs = s["by_symbol"]
        ks = list(bs)
        if ks:
            L.append("- Coins (total R): best " + ", ".join(
                f"{k} {bs[k]['R']:+.1f} ({bs[k]['trades']})" for k in ks[::-1][:4])
                + "; worst " + ", ".join(f"{k} {bs[k]['R']:+.1f} ({bs[k]['trades']})"
                                         for k in ks[:3]) + ".")
        L.append(f"- Exits: {s['exit_reasons']}.")
        L.append(f"- Gates failed: {', '.join(s['gates_failed']) or 'none'}.\n")
    L.append("## Method notes and limitations\n")
    L.append(
        "- Point-in-time universe: meme flag, listed >= 30 days, 30-day mean daily quote volume "
        f">= 20M USDT (mean {dev['eligible_memes_per_day']['dev_oos_mean']:.1f} eligible memes "
        f"per day in dev OOS, {dev['eligible_memes_per_day']['dev_is_mean']:.1f} in dev IS), "
        "complete day. Rankings use closed days only; orders fill at the next 1h (or 4h) open. "
        "Shift tests for the ranking and the edge monitor: `tests/test_lab_rotation.py`.\n"
        "- The dev run loaded no bar or funding settlement at or after 2026-05-01; the holdout "
        "ran once afterwards with the frozen defaults (`holdout.json`).\n"
        "- Minimum notional: owner's exchangeInfo values (BTC 50 USDT / 0.001 BTC, ETH 20, "
        "default 5); memes use the default 5 USDT, an ESTIMATE for memes. With 1% risk at "
        "110 USDT (1.10 USDT at risk) any stop wider than ~22% cannot be placed.\n"
        "- Equity for sizing is closed-trade equity; drawdowns and worst months are "
        "mark-to-market at daily closes (intraday swings are larger). Monte Carlo compounds "
        "trades one after another, so it understates overlapping-position drawdowns.\n"
        "- Delisted memes are included; a position open at delisting is closed at the last "
        "real trade minus 2% (ESTIMATE). Hype proxies are exchange data only (no news archive).\n"
        "- Regime months in dev OOS: " + ", ".join(f"{k} {v}" for k, v in
                                                   dev["regime_months"].items()) + ".\n"
        "- Bias disclosure: LAB had seen meme results for 2024-11..2026-10 before this design "
        "(see DESIGN.md). R3 (M11) and R5 (short the faders) were informed by that, so their "
        "holdout is not fully clean.\n")
    (OUT / "REPORT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    # ---------------------------------------------------------------- top.json
    ranked = sorted(S, key=lambda sid: (len(status[sid]),
                                         -(S[sid]["default"]["oos"]["total_return"] or 0)))
    top = dict(
        status="QUALIFIED" if qual else "NOT_QUALIFIED",
        qualified=qual,
        summary=("No meme rotation strategy passed every gate; nothing to paper-trade as a "
                 "live candidate." if not qual else f"Qualified (paper only): {', '.join(qual)}"),
        variants_tried=nvar, holdout_run=ho is not None,
        best_by_gates=ranked[0],
        strategies={sid: dict(
            name=S[sid]["name"], default=S[sid]["default_key"],
            status="QUALIFIED" if not status[sid] else "NOT_QUALIFIED",
            reasons=status[sid],
            dev_oos=dict(trades=S[sid]["default"]["oos"]["trades"],
                         exp_R=S[sid]["default"]["oos"]["exp_R"],
                         total_return=S[sid]["default"]["oos"]["total_return"],
                         cagr=S[sid]["default"]["oos"]["cagr"],
                         max_dd_mtm=S[sid]["default"]["oos"]["max_dd_mtm"]),
            dev_oos_2x_total_return=S[sid]["default"]["oos_2x"]["total_return"],
            wf_total_R=S[sid]["wf"]["total_R"], wf_total_return=S[sid]["wf"]["total_return"],
            holdout_total_return=(ho["strategies"][sid]["base"]["total_return"] if ho else None),
            holdout_2x_total_return=(ho["strategies"][sid]["both2x"]["total_return"]
                                     if ho else None),
            holdout_trades=(ho["strategies"][sid]["base"]["trades"] if ho else None),
            r4_base=S[sid].get("r4_base"))
            for sid in S},
        benchmarks_dev_oos=dict(btc_perp_cagr=b["btc_perp"]["cagr"],
                                btc_spot_cagr=b["btc_spot"]["cagr"],
                                meme_basket_cagr=b["meme_basket"]["cagr"]),
        benchmarks_holdout=(dict(btc_perp_total=ho["bench"]["btc_perp"]["total_return"],
                                 btc_spot_total=ho["bench"]["btc_spot"]["total_return"],
                                 meme_basket_total=ho["bench"]["meme_basket"]["total_return"])
                            if ho else None),
        note="PAPER ONLY. Source: research/lab/meme_rotation/dev_results.json, holdout.json; "
             "code src/lab/rotation.py; design research/lab/meme_rotation/DESIGN.md.")
    (OUT / "top.json").write_text(json.dumps(top, indent=1))
    print("wrote REPORT.md and top.json;", top["status"], qual)


if __name__ == "__main__":
    main()
